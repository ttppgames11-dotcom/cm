class HistoricalFigure {
  const HistoricalFigure({
    required this.id,
    required this.name,
    required this.category,
    required this.badge,
    required this.description,
    this.warriorId,
    this.imageAsset,
  });

  final String id;
  final String name;

  /// chhatrapati | peshwa | virangana | yodha
  final String category;
  final String badge;
  final String description;

  /// Detail page in the app (`/warrior/:id`), when one exists.
  final String? warriorId;
  final String? imageAsset;
}

class Battle {
  const Battle({
    required this.id,
    required this.era,
    required this.date,
    required this.location,
    required this.title,
    required this.description,
    required this.commander,
    required this.importance,
    required this.reference,
  });

  final String id;

  /// shivaji | peshwa | anglo
  final String era;
  final String date;
  final String location;
  final String title;
  final String description;
  final String commander;
  final String importance;
  final String reference;
}

class WarriorProfile {
  const WarriorProfile({
    required this.id,
    required this.name,
    required this.title,
    required this.role,
    required this.deed,
    required this.icon,
    this.warriorId,
  });

  final String id;
  final String name;
  final String title;
  final String role;
  final String deed;
  final String icon;
  final String? warriorId;
}

