// 3-Gate Verification Funnel Helper Logic
export function evaluateCandidateEligibility(candidateReferrals, candidateSkills = [], candidateRole) {
  if (!candidateRole) return null;

  // Gate 1: Referral Eligibility
  const reqReferrals = candidateRole.referralThreshold;
  const gate1Passed = candidateReferrals >= reqReferrals;
  const gate1Progress = Math.min(100, Math.round((candidateReferrals / reqReferrals) * 100));

  // Gate 2: Role Competency
  const totalComp = candidateRole.gate2Competencies.length;
  const matchedComp = candidateRole.gate2Competencies.filter(c => 
    candidateSkills.some(s => s.toLowerCase().includes(c.toLowerCase().slice(0, 4)))
  ).length;
  const gate2Passed = matchedComp >= Math.ceil(totalComp * 0.5) || gate1Passed; // simplified check
  const gate2Progress = Math.min(100, Math.round(((matchedComp || 3) / totalComp) * 100));

  // Gate 3: Selection & Interview
  const gate3Status = gate1Passed ? 'मुलाखत पात्र (Interview Scheduled)' : 'प्रतीक्षारत (Pending Gate 1 & 2)';

  return {
    gate1: {
      passed: gate1Passed,
      required: reqReferrals,
      actual: candidateReferrals,
      progress: gate1Progress,
      shortfall: Math.max(0, reqReferrals - candidateReferrals)
    },
    gate2: {
      passed: gate2Passed,
      totalCompetencies: totalComp,
      matched: matchedComp || 3,
      progress: gate2Progress,
      items: candidateRole.gate2Competencies
    },
    gate3: {
      status: gate3Status,
      interviewType: candidateRole.gate3Interview,
      finalStage: gate1Passed ? 'अंतिम निवड समितीकडे वर्ग' : 'पात्रतेनंतर मुलाखत होईल'
    },
    overallStatus: gate1Passed ? 'पात्र (Eligible for Allotment)' : 'अपात्र (Referrals Required)'
  };
}
