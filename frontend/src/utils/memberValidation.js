// Comprehensive non-repetitive input validation for forms (phone, email, name)
export function checkRepetitiveInput(value, type = 'text') {
  if (!value) return { isValid: true };
  const str = String(value).trim();

  if (type === 'phone' || type === 'mobile') {
    const digits = str.replace(/\D/g, '');
    if (digits.length !== 10) {
      return {
        isValid: false,
        message: 'कृपया बरोबर १० अंकी मोबाईल नंबर प्रविष्ट करा.'
      };
    }
    // Check all identical digits (e.g. 1111111111, 9999999999, 0000000000)
    if (/^(.)\1{9}$/.test(digits)) {
      return {
        isValid: false,
        message: 'अवैध नंबर: एकाच अंकाची पुनरावृत्ती (Repetitive digits) स्वीकारली जात नाही. कृपया खरा नंबर टाका.'
      };
    }
    // Check repetitive 2-digit sequence (e.g. 1212121212, 9898989898)
    if (/^(\d{2})\1{4}$/.test(digits)) {
      return {
        isValid: false,
        message: 'अवैध नंबर: पुनरावृत्ती पॅटर्न (Repetitive pattern) स्वीकारला जात नाही.'
      };
    }
    // Check trivial ascending or descending sequence
    if (digits === '1234567890' || digits === '0123456789' || digits === '9876543210' || digits === '0987654321') {
      return {
        isValid: false,
        message: 'अवैध नंबर: साधी अनुक्रमिक (Sequential) संख्या चालणार नाही. कृपया खरा नंबर टाका.'
      };
    }
    return { isValid: true };
  }

  if (type === 'name') {
    // Check single repeated letter name like aaaaa, bbbbb
    if (/^(.)\1{4,}$/i.test(str.replace(/\s/g, ''))) {
      return {
        isValid: false,
        message: 'कृपया खरे व पूर्ण नाव प्रविष्ट करा (पुनरावृत्ती अक्षरे अमान्य).'
      };
    }
    if (str.length < 3) {
      return {
        isValid: false,
        message: 'नाव किमान ३ अक्षरांचे असणे आवश्यक आहे.'
      };
    }
    return { isValid: true };
  }

  if (type === 'email') {
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(str)) {
      return {
        isValid: false,
        message: 'कृपया वैध ईमेल पत्ता प्रविष्ट करा.'
      };
    }
    const [userPart] = str.split('@');
    if (/^(.)\1{3,}$/.test(userPart)) {
      return {
        isValid: false,
        message: 'कृपया खरा ईमेल आयडी प्रविष्ट करा (पुनरावृत्ती अमान्य).'
      };
    }
    return { isValid: true };
  }

  return { isValid: true };
}
